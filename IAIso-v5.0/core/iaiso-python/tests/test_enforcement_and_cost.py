def test_policy_accepts_both_modes():
    from iaiso.policy import _validate
    _validate({"version": "1", "enforcement_mode": "strict"})
    _validate({"version": "1", "enforcement_mode": "permissive"})


def test_policy_rejects_unknown_mode():
    from iaiso.policy import PolicyError, _validate
    with pytest.raises(PolicyError, match="enforcement_mode"):
        _validate({"version": "1", "enforcement_mode": "advisory"})


def test_policy_rejects_wrong_type():
    from iaiso.policy import PolicyError, _validate
    with pytest.raises(PolicyError, match="enforcement_mode"):
        _validate({"version": "1", "enforcement_mode": 1})
