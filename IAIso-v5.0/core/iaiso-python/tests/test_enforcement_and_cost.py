"""Regression tests for the `enforcement_mode` boot guard (WI-4) and the
cost-governance surface (WI-5).

These sit alongside the existing suite; they do not replace it.
"""

from __future__ import annotations

import logging

import pytest

from iaiso.audit import MemorySink, NullSink
from iaiso.core import (
    ENFORCEMENT_PERMISSIVE,
    ENFORCEMENT_STRICT,
    PressureConfig,
    PressureEngine,
    StrictModeError,
)
from iaiso.core.engine import Lifecycle, StepInput, StepOutcome


def calibrated(**overrides) -> PressureConfig:
    """A config that has been moved off library defaults."""
    base = dict(token_coefficient=0.011)
    base.update(overrides)
    return PressureConfig(**base)


def scripted(values):
    it = iter(values)
    last = [0.0]

    def clock():
        try:
            last[0] = next(it)
        except StopIteration:
            pass
        return last[0]

    return clock


# --------------------------------------------------------------------------
# WI-4 — boot guard
# --------------------------------------------------------------------------

def test_strict_refuses_null_sink():
    with pytest.raises(StrictModeError) as exc:
        PressureEngine(calibrated(), execution_id="t",
                       audit_sink=NullSink(),
                       enforcement_mode=ENFORCEMENT_STRICT)
    assert "NullSink" in str(exc.value)


def test_strict_refuses_missing_sink():
    # Omitting the sink entirely is the same degraded condition as passing
    # NullSink explicitly — it must not be a way around the guard.
    with pytest.raises(StrictModeError):
        PressureEngine(calibrated(), execution_id="t",
                       enforcement_mode=ENFORCEMENT_STRICT)


def test_strict_refuses_post_release_lock_disabled():
    cfg = calibrated(post_release_lock=False)
    with pytest.raises(StrictModeError) as exc:
        PressureEngine(cfg, execution_id="t", audit_sink=MemorySink(),
                       enforcement_mode=ENFORCEMENT_STRICT)
    assert "post_release_lock" in str(exc.value)


def test_strict_refuses_uncalibrated_defaults():
    with pytest.raises(StrictModeError) as exc:
        PressureEngine(PressureConfig(), execution_id="t",
                       audit_sink=MemorySink(),
                       enforcement_mode=ENFORCEMENT_STRICT)
    assert "calibrat" in str(exc.value)


def test_strict_accepts_defaults_with_calibration_artifact():
    engine = PressureEngine(PressureConfig(), execution_id="t",
                            audit_sink=MemorySink(),
                            enforcement_mode=ENFORCEMENT_STRICT,
                            calibration_artifact="calibration/2026-07-01.json")
    assert engine.enforcement_mode == ENFORCEMENT_STRICT


def test_strict_refuses_autogenerated_hs256_key():
    with pytest.raises(StrictModeError) as exc:
        PressureEngine(calibrated(), execution_id="t", audit_sink=MemorySink(),
                       enforcement_mode=ENFORCEMENT_STRICT,
                       consent_algorithm="HS256",
                       consent_key_auto_generated=True)
    assert "HS256" in str(exc.value)


def test_strict_accepts_a_sound_config():
    engine = PressureEngine(calibrated(), execution_id="t",
                            audit_sink=MemorySink(),
                            enforcement_mode=ENFORCEMENT_STRICT)
    assert engine.enforcement_mode == ENFORCEMENT_STRICT


def test_permissive_is_the_default_and_proceeds():
    engine = PressureEngine(PressureConfig(), execution_id="t")
    assert engine.enforcement_mode == ENFORCEMENT_PERMISSIVE


def test_permissive_warns_but_does_not_raise(caplog):
    import iaiso.core.engine as eng
    eng._warned.clear()
    with caplog.at_level(logging.WARNING, logger="iaiso"):
        PressureEngine(PressureConfig(), execution_id="t", audit_sink=NullSink())
    assert any("NullSink" in r.getMessage() for r in caplog.records)


def test_unknown_enforcement_mode_is_a_config_error():
    with pytest.raises(ValueError, match="enforcement_mode"):
        PressureEngine(calibrated(), execution_id="t", audit_sink=MemorySink(),
                       enforcement_mode="advisory")


def test_strict_refusal_leaves_nothing_constructed():
    # A half-built engine that emitted engine.init before refusing would be a
    # lie in the audit log.
    sink = MemorySink()
    with pytest.raises(StrictModeError):
        PressureEngine(PressureConfig(post_release_lock=False),
                       execution_id="t", audit_sink=sink,
                       enforcement_mode=ENFORCEMENT_STRICT)
    assert len(sink.events) == 0


