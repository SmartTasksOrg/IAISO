# WI-5 — cost governance
# --------------------------------------------------------------------------

def cost_config(**overrides) -> PressureConfig:
    base = dict(dissipation_per_step=0.0,
                model_costs={"frontier": 15.0, "small": 0.5})
    base.update(overrides)
    return PressureConfig(**base)


def test_spend_is_tracked_and_emitted():
    sink = MemorySink()
    engine = PressureEngine(cost_config(), execution_id="t", audit_sink=sink,
                            clock=scripted([0.0, 1.0, 2.0]))
    engine.step(StepInput(tokens=100_000, model="frontier"))
    assert engine.spend_usd == pytest.approx(1.5)

    steps = [e for e in sink.events if e.kind == "engine.step"]
    assert steps and "spend_usd" in steps[0].data


def test_spend_field_absent_without_model_costs():
    # Existing consumers of the frozen 1.0 envelope must not see a new key.
    sink = MemorySink()
    engine = PressureEngine(PressureConfig(dissipation_per_step=0.0),
                            execution_id="t", audit_sink=sink,
                            clock=scripted([0.0, 1.0]))
    engine.step(StepInput(tokens=1000))
    steps = [e for e in sink.events if e.kind == "engine.step"]
    assert steps and "spend_usd" not in steps[0].data


def test_unknown_model_costs_nothing():
    engine = PressureEngine(cost_config(), execution_id="t",
                            audit_sink=MemorySink(), clock=scripted([0.0, 1.0]))
    engine.step(StepInput(tokens=1_000_000, model="unpriced"))
    assert engine.spend_usd == 0.0


def test_budget_exceeded_reuses_the_lock_path():
    sink = MemorySink()
    engine = PressureEngine(cost_config(budget_usd=1.0), execution_id="t",
                            audit_sink=sink, clock=scripted([0.0, 1.0, 2.0]))
    outcome = engine.step(StepInput(tokens=100_000, model="frontier"))

    assert outcome is StepOutcome.LOCKED
    assert engine.lifecycle is Lifecycle.LOCKED

    locked = [e for e in sink.events if e.kind == "engine.locked"]
    assert locked and locked[0].data["reason"] == "budget_exceeded"

    # No new lifecycle state was invented.
    assert {e.kind for e in sink.events} <= {
        "engine.init", "engine.step", "engine.locked",
        "engine.release", "engine.reset", "engine.step.rejected",
    }


def test_budget_locked_engine_rejects_further_steps():
    engine = PressureEngine(cost_config(budget_usd=1.0), execution_id="t",
                            audit_sink=MemorySink(),
                            clock=scripted([0.0, 1.0, 2.0, 3.0]))
    engine.step(StepInput(tokens=100_000, model="frontier"))
    assert engine.step(StepInput(tokens=1)) is StepOutcome.LOCKED


def test_reset_clears_spend():
    engine = PressureEngine(cost_config(), execution_id="t",
                            audit_sink=MemorySink(),
                            clock=scripted([0.0, 1.0, 2.0]))
    engine.step(StepInput(tokens=100_000, model="frontier"))
    assert engine.spend_usd > 0
    engine.reset()
    assert engine.spend_usd == 0.0


def test_negative_budget_is_a_config_error():
    with pytest.raises(ValueError, match="budget_usd"):
        PressureConfig(budget_usd=-1.0)


def test_negative_model_cost_is_a_config_error():
    with pytest.raises(ValueError, match="model_costs"):
        PressureConfig(model_costs={"frontier": -1.0})


